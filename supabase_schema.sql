-- ==============================================================================
-- VTAB REVENUE INTELLIGENCE & MARKETING AGENT - SUPABASE SCHEMA
-- Run this script in your Supabase Project -> SQL Editor
-- ==============================================================================

-- Enable UUID extension
create extension if not exists "uuid-ossp";

-- 1. LEADS TABLE (Prospecting, Intent Signals & Date Tracking)
create table if not exists public.leads (
    id bigint generated by default as identity primary key,
    name text not null,
    role text not null,
    company text not null,
    initials text not null,
    source text not null,
    excerpt text not null,
    intent integer not null default 75,
    color text default 'sage',
    added_this_week boolean default true,
    fetched_date text not null,
    fetched_time text not null,
    fetched_timestamp bigint not null,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. KNOWLEDGE SOURCES TABLE (RAG Knowledge Bases & Docs)
create table if not exists public.knowledge_sources (
    id text primary key,
    name text not null,
    kind text not null, -- 'Website' | 'PDF'
    detail text not null,
    chunks integer not null default 0,
    status text not null default 'Ready',
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 3. KNOWLEDGE CHUNKS TABLE (Searchable Embeddings / Passages)
create table if not exists public.knowledge_chunks (
    id bigint generated by default as identity primary key,
    source_id text references public.knowledge_sources(id) on delete cascade,
    source_name text not null,
    text text not null,
    token_count integer default 150,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 4. CAMPAIGN RUNS & DELIVERABLES (Marketing Bot Multi-Agent Output)
create table if not exists public.campaigns (
    id text primary key,
    brief text not null,
    knowledge_base text not null,
    status text not null default 'Completed',
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    social_copy text,
    twitter_thread jsonb,
    cold_email jsonb,
    newsletter jsonb,
    visual_direction jsonb,
    dm_copy text,
    agent_logs jsonb default '[]'::jsonb
);

-- 5. APPROVAL QUEUE TABLE (Human-in-the-Loop Safeguard)
create table if not exists public.approvals (
    id text primary key,
    type text not null, -- 'LinkedIn DM' | 'Campaign Post' | 'Outreach sequence' | 'Twitter Thread'
    title text not null,
    recipient text not null,
    detail text not null,
    badge text not null,
    badge_type text default 'neutral',
    status text not null default 'Pending review', -- 'Pending review' | 'Approved' | 'Rejected'
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 6. WORKFLOWS TABLE (n8n Interactive Graph Canvas)
create table if not exists public.workflows (
    id text primary key,
    title text not null,
    brief text not null,
    knowledge_base text not null,
    status text not null default 'Completed',
    created_at text not null,
    duration text not null default '4.7s',
    items_produced integer default 3,
    trigger_type text default 'Manual Brief',
    tags text[] default array['Marketing Bot', 'Multi-Agent'],
    nodes jsonb not null default '[]'::jsonb,
    edges jsonb not null default '[]'::jsonb,
    outputs jsonb not null default '{}'::jsonb
);

-- 7. SOCIAL POSTS (Facebook, Instagram, Reddit, X / Twitter)
create table if not exists public.social_posts (
    id bigint generated by default as identity primary key,
    platform text not null, -- 'linkedin' | 'facebook' | 'instagram' | 'reddit' | 'x'
    status text not null default 'draft', -- 'draft' | 'pending_approval' | 'published' | 'failed'
    title text,
    content text not null,
    media_url text,
    external_post_id text,
    scheduled_for timestamp with time zone,
    published_at timestamp with time zone,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- ==============================================================================
-- ROW LEVEL SECURITY (RLS) - Enable public read/write with anon key for app
-- ==============================================================================
alter table public.leads enable row level security;
alter table public.knowledge_sources enable row level security;
alter table public.knowledge_chunks enable row level security;
alter table public.campaigns enable row level security;
alter table public.approvals enable row level security;
alter table public.workflows enable row level security;
alter table public.social_posts enable row level security;

-- Create policies allowing full access via anon key for development
create policy "Allow all leads" on public.leads for all using (true) with check (true);
create policy "Allow all sources" on public.knowledge_sources for all using (true) with check (true);
create policy "Allow all chunks" on public.knowledge_chunks for all using (true) with check (true);
create policy "Allow all campaigns" on public.campaigns for all using (true) with check (true);
create policy "Allow all approvals" on public.approvals for all using (true) with check (true);
create policy "Allow all workflows" on public.workflows for all using (true) with check (true);
-- 8. CREATIVE HISTORY (Recent-creative memory per workspace for visual variety)
create table if not exists public.creative_history (
    id bigint generated by default as identity primary key,
    workspace_id text not null default 'northstar-labs',
    campaign_id text,
    platform text,
    style text not null,
    dominant_palette text not null,
    main_subject text not null,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.creative_history enable row level security;
create policy "Allow all creative_history" on public.creative_history for all using (true) with check (true);
create policy "Allow all social_posts" on public.social_posts for all using (true) with check (true);
